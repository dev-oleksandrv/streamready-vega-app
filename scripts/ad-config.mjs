#!/usr/bin/env node
// Writes src/app/config/adConfig.generated.ts from the SR_AD_TAG_* variables (.env or environment).
// A missing or invalid tag switches that ad slot off, so a build without tags is an ad-free app (ADR 0013).
// Tag URLs identify the ad account: this script never prints them, only which slots are on.

import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');
const outFile = join(root, 'src/app/config/adConfig.generated.ts');

const SLOTS = [
  ['result', 'SR_AD_TAG_RESULT'],
  ['home', 'SR_AD_TAG_HOME'],
  ['video', 'SR_AD_TAG_VIDEO'],
];

if (existsSync(envFile)) {
  // Real environment variables win over .env.
  process.loadEnvFile(envFile);
}

function readTag(name) {
  const value = (process.env[name] ?? '').trim();
  if (value === '') {
    return '';
  }
  if (!value.startsWith('https://')) {
    console.warn(`ad-config: ${name} is not an https:// URL, slot off`);
    return '';
  }
  return value;
}

const tags = Object.fromEntries(SLOTS.map(([slot, name]) => [slot, readTag(name)]));

const content = `// Generated by scripts/ad-config.mjs from .env / environment. Do not edit. Gitignored.
export const AD_TAGS = {
  result: ${JSON.stringify(tags.result)},
  home: ${JSON.stringify(tags.home)},
  video: ${JSON.stringify(tags.video)},
} as const;
`;

// Skip the write when nothing changed, so Metro and tsc don't see a fresh file on every install.
const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
if (previous !== content) {
  writeFileSync(outFile, content);
}

const summary = SLOTS.map(([slot]) => `${slot} ${tags[slot] ? 'on' : 'off'}`).join(', ');
console.log(`ad-config: ${summary}`);
